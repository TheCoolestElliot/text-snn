def test_uer_counts_only_qualifying_texts_and_reports_the_fraction():
    """The fixed window is what stops a shorter-reply arm winning by length, so
    a short text must leave the DENOMINATOR, not be scored over less text."""
    drift = _pad("There was a sheep. The pig was big.")
    clean = _pad("There was a pig. The pig was big.")
    short_drift = "There was a sheep. The pig was big."
    assert len(short_drift) < 200 <= min(len(drift), len(clean))

    r = uer([drift, clean, clean, short_drift, short_drift])
    assert (r["k"], r["n"], r["n_total"]) == (1, 3, 5)
    assert r["rate"] == pytest.approx(1 / 3)
    assert r["qualifying_fraction"] == pytest.approx(3 / 5)
    assert r["window"] == 200
    assert set(r) == {"rate", "k", "n", "ci", "qualifying_fraction", "n_total", "window"}
    lo, hi = r["ci"]
    assert 0.0 <= lo < r["rate"] < hi <= 1.0


def test_uer_qualifying_boundary_is_len_at_least_window():
    text = _pad("There was a sheep. The pig was big.")
    assert uer([text[:200]])["n"] == 1
    assert uer([text[:199]])["n"] == 0
    assert uer([text[:199]], window=199)["n"] == 1


def test_uer_with_nothing_qualifying_is_no_measurement_not_a_perfect_score():
    r = uer(["The pig was big."])
    assert r["rate"] is None and (r["k"], r["n"], r["n_total"]) == (0, 0, 1)
    assert r["ci"] == [0.0, 1.0]
    assert r["qualifying_fraction"] == 0.0
    empty = uer([])
    assert empty["rate"] is None and empty["qualifying_fraction"] is None


def test_uer_counts_texts_not_entities():
    """k is replies with AT LEAST ONE unintroduced entity, never a sum of them."""
    two = _pad("There was a sheep. The pig was big. The cow was sad.")
    assert len(unintroduced_entities(two)) == 2
    assert uer([two])["k"] == 1


def test_uer_accepts_a_generator_and_checks_contexts_length():
    text = _pad("The pig was big.")
    assert uer(t for t in [text])["k"] == 1
    assert uer([text], contexts=["a story about a pig"])["k"] == 0
    with pytest.raises(ValueError, match="one prompt per text"):
        uer([text, text], contexts=["a story about a pig"])


def test_wilson_interval_matches_the_conventions_worked_example():
    """`docs/chat/CONVENTIONS.md` §1: 6/48 -> [0.059, 0.247]. The interval is
    inlined in `coherence` because `snnchat.quality` imports torch, so it is
    checked against the documented value rather than against that function."""
    lo, hi = coherence.wilson_interval(6, 48)
    assert lo == pytest.approx(0.0586, abs=5e-4)
    assert hi == pytest.approx(0.247, abs=5e-4)
    assert coherence.wilson_interval(0, 0) == (0.0, 1.0)
    lo0, hi0 = coherence.wilson_interval(0, 50)
    assert lo0 == 0.0 and 0.0 < hi0 < 0.1


