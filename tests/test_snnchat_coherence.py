def test_a_definite_subject_never_introduced_is_flagged():
    """The failure the instrument was built for, in its smallest form."""
    text = "Once upon a time there was a sheep. The pig was big."
    assert unintroduced_entities(text) == ["pig"]


def test_a_definite_subject_introduced_earlier_is_clean():
    text = "Once upon a time there was a pig. The pig was big."
    assert unintroduced_entities(text) == []


def test_an_entity_is_reported_once_and_in_order_of_appearance():
    """The second "The pig" has the first one before it: that IS an earlier
    occurrence, so one drifted entity is one entry however long it is dwelt on."""
    text = "There was a sheep. The pig was big. The cow was sad. The pig was pink."
    assert unintroduced_entities(text) == ["pig", "cow"]


def test_the_head_is_the_word_before_the_verb_not_a_modifier():
    text = "There was a girl. The big red ball was shiny."
    assert unintroduced_entities(text) == ["ball"]
    # ...and an introduced MODIFIER does not introduce the head.
    assert unintroduced_entities("There was a red hat. The red ball was shiny.") == ["ball"]


def test_plural_tolerance_runs_in_both_directions():
    """"a bird ... The birds were" and "two birds ... The bird was" are both
    introduced. The prototype looked the head up as written and so flagged the
    first of these."""
    assert unintroduced_entities("She saw a bird. The birds were loud.") == []
    assert unintroduced_entities("She saw two birds. The bird was loud.") == []
    assert unintroduced_entities("He saw a fox. The foxes were quick.") == []
    assert unintroduced_entities("He saw two foxes. The fox was quick.") == []


def test_plural_tolerance_is_whole_word_not_substring():
    """"cat" inside "catalog" or "scatter" introduces nothing."""
    assert unintroduced_entities("She read a catalog. The cat was soft.") == ["cat"]
    assert unintroduced_entities("Leaves scatter. The cat was soft.") == ["cat"]


def test_an_object_definite_is_not_a_subject():
    """"went to the park" is a bridging definite in object position, which
    English does not require an introduction for. No verb follows it."""
    assert unintroduced_entities("Tim went to the park. He kicked the ball.") == []


def test_function_words_are_never_heads():
    """The prototype's first defect: its commonest corpus "entity" was "and"."""
    assert unintroduced_entities("Tim took the hat and went home.") == []
    assert unintroduced_entities("She liked the box because it was red.") == []
    assert unintroduced_entities("He saw the dog that they had fed.") == []
    # With the stoplist off, the defect is back -- which is what makes the
    # stoplist's effect a measurement and not a claim.
    assert unintroduced_entities("Tim took the hat and went home.", stoplist=False) == ["and"]


def test_unique_reference_nouns_are_never_heads():
    """"The sun was shining" introduces nothing and needs no introduction."""
    text = "One day the sun was bright. The sky was blue and the wind was soft."
    assert unintroduced_entities(text) == []
    assert unintroduced_entities(text, stoplist=False) == ["sun", "sky", "wind"]


def test_a_noun_phrase_does_not_span_a_conjunction():
    """Why the stoplist bars MODIFIERS inside the pattern, not just heads after it.

    "the [box and] Tim was" is not a noun phrase: "Tim" is the subject of the
    next clause and needs no introduction. A filter on the returned head could
    not reject it -- "tim" is not a function word -- so the bar has to sit on
    the modifier. The subject after the conjunction is still read when it is a
    definite of its own.
    """
    text = "There was a boy. He opened the box and Tim was glad."
    assert unintroduced_entities(text) == []
    assert unintroduced_entities(text, stoplist=False) == ["tim"]
    text = "There was a boy. He dropped the hat and the dog was sad."
    assert unintroduced_entities(text) == ["dog"]


def test_the_window_is_respected():
    """Only a subject that ENDS inside the window counts."""
    lead = _pad("There was a sheep.", 210)
    text = lead + " The pig was big."
    assert len(lead) >= 200
    assert unintroduced_entities(text) == []
    assert unintroduced_entities(text, window=len(text)) == ["pig"]
    # And one that ends exactly at the window edge is inside it.
    head = "There was a sheep. The pig was"
    assert unintroduced_entities(head + " big.", window=len(head)) == ["pig"]
    assert unintroduced_entities(head + " big.", window=len(head) - 1) == []


def test_a_verb_is_not_recognised_in_the_prefix_of_a_cut_word():
    """Why the pattern runs over the whole text and is cut afterwards.

    Cut at "The pig was|hing", `text[:window]` ends in "was" and a pattern run
    over the cut string would see a story verb that the text does not contain.
    """
    text = "There was a sheep. The pig washing itself smiled."
    cut = text.index("washing") + 3
    assert text[:cut].endswith("The pig was")
    assert unintroduced_entities(text, window=cut) == []


def test_context_counts_as_introduced_and_is_off_by_default():
    reply = "The pig was big. The cow was sad."
    assert unintroduced_entities(reply) == ["pig", "cow"]
    assert unintroduced_entities(reply, context="tell me a story about a pig") == ["cow"]
    assert unintroduced_entities(reply, context="tell me a story about pigs") == ["cow"]


