def test_anchored_topic_needs_an_introduction_and_a_second_mention():
    story = "Once upon a time there was a little brown penguin. The penguin was very fit."
    assert anchored_topic(story, "penguin")
    # Mentioned in passing at the end of a drifting story: a bare-mention hit,
    # not an anchored one.
    drift = "There was a sheep. The pig was very big. Then the penguin was very fit."
    assert not anchored_topic(drift, "penguin")
    # Introduced but never referred back to.
    assert not anchored_topic("There was a penguin. The pig was big.", "penguin")
    # Twice, but neither introduced with a/an nor in the first sentence.
    twice = "There was a sheep. The penguin was big. The penguin was fit."
    assert not anchored_topic(twice, "penguin")


def test_anchored_topic_first_sentence_and_plurals():
    # No a/an, but in the first sentence: anchored.
    assert anchored_topic("Penguins are fun. One penguin was very fit.", "penguin")
    assert anchored_topic("She had an apple. The apples were red.", "apples")
    # Whole word only, in the anchor and in the count of mentions alike.
    assert not anchored_topic("A catalog is a catalog.", "cat")
    assert not anchored_topic("There was a cat. She read the catalog.", "cat")


