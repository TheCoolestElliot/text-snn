def test_importing_coherence_does_not_import_torch():
    """In a fresh interpreter, because this process has torch loaded already.

    `json.dumps` embeds the path: the repository path contains an apostrophe.
    numpy is held to the same bar -- the module promises pure Python.
    """
    src = json.dumps(os.path.join(REPO, "src"))
    code = (
        f"import sys; sys.path.insert(0, {src}); import snnchat.coherence; "
        "bad = [m for m in ('torch', 'numpy', 'snnchat.rerank', 'snnchat.quality') "
        "if m in sys.modules]; print(bad); sys.exit(1 if bad else 0)"
    )
    out = subprocess.run(
        [sys.executable, "-c", code], capture_output=True, text=True, cwd=REPO, timeout=120
    )
    assert out.returncode == 0, out.stdout + out.stderr


