def test_fixture_is_what_it_claims():
    with open(FIXTURE, encoding="utf-8") as fh:
        doc = json.load(fh)
    rows = doc["rows"]
    assert doc["n"] == len(rows) and 60 <= len(rows) <= 120
    assert os.path.getsize(FIXTURE) < 80_000
    assert all(len(r["story"]) >= coherence.WINDOW for r in rows)
    assert all(r["prompt"] and r["story"][-1] in ".!?\"'" for r in rows)
    assert len({r["story"] for r in rows}) == len(rows)
    assert len(doc["source_sha256"]) == 64 and "stories_topic.val.bin" in doc["source"]


def test_mutations_do_what_their_names_say():
    a = "A one. A two. A three. A four. A five."
    b = "B one. B two. B three."
    assert coherence.split_sentences(a) == ["A one.", "A two.", "A three.", "A four.", "A five."]
    # Odd indices come from `b` while `b` lasts; the length stays `a`'s.
    assert coherence.replace_alternate_sentences(a, b) == "A one. B two. A three. A four. A five."
    assert coherence.interleave_sentences(a, b) == "A one. B one. A two. B two. A three. B three."


def test_replace_alternate_sentences_raises_uer_by_a_clear_margin():
    """CAN-FAIL. Deleting introductions while keeping the references to them is
    the shape of the model's drift, and if the instrument does not move under it
    the instrument measures nothing.

    Measured on the fixture (2026-09-21): clean 3/120 = 0.025, replace-alternate
    32/120 = 0.267 -- 29 more flagged stories. The bars below leave slack (20 of
    the 29; a rate ratio of 5 against the measured 10.7) and additionally demand
    that the two Wilson intervals do not overlap, so the test cannot be passed
    by a change that leaves the instrument merely noisy. Every mutant still
    qualifies, so the rise is not a change of denominator.
    """
    r = _readings()
    clean, replace = r["clean"], r["replace"]
    assert clean["n"] == replace["n"] == clean["n_total"] == 120
    assert replace["k"] - clean["k"] >= 20
    assert replace["rate"] >= 5 * clean["rate"]
    assert replace["ci"][0] > clean["ci"][1]
    # The clean corpus is near its floor: the instrument is not simply firing
    # on everything.
    assert clean["rate"] <= 0.06


def test_plain_interleave_is_not_detected_known_blindness():
    """DOCUMENTED BLINDNESS -- a known limit being pinned, NOT a desired property.

    Two complete stories shuffled sentence by sentence (A1, B1, A2, B2, ...) are
    less coherent to a reader than either mutant above, and UER reads them as
    CLEAN: nothing was deleted, so each story still introduces its own entities
    with "a" before it says "the". Measured on the fixture (2026-09-21):
    interleave 2/120 = 0.017 against clean 3/120 = 0.025 -- it reads BELOW the
    clean text, because the window now holds half as much of each story. The
    full corpus reference says the same (`coherence_v14.json`,
    `corpus.mutations.interleave`).

    If this test ever FAILS because the interleave rate rose, that is an
    improvement to the instrument, not a regression: update the module
    docstring's "WHAT IT CANNOT SEE" item 1 and this test together. Until then
    nobody may quote a low UER as evidence that a reply holds together.
    """
    r = _readings()
    assert r["interleave"]["n"] == 120
    assert r["interleave"]["rate"] <= r["clean"]["rate"] + 0.02
    # The contrast with the detected mutation, on the same pairs.
    assert r["interleave"]["rate"] < 0.25 * r["replace"]["rate"]


