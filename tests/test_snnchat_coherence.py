"""Tests for `snnchat.coherence`: the unintroduced-entity rate (UER@200).

CPU only, and CI has no `data/` directory, so everything that needs
corpus text reads ONE committed fixture:

    tests/fixtures/chat_stories_uer.json

HOW THE FIXTURE WAS MADE, AND HOW IT WAS CHECKED
------------------------------------------------
`python scripts/chat/coherence_score.py --data-dir <data/chat> --write-fixture
tests/fixtures/chat_stories_uer.json`. It is the FIRST 120 conversations of
`data/chat/stories_topic.val.bin` that have both a `<|user|>` and a `<|bot|>`
turn, in file order, decoded with `ChatTokenizer.decode_visible`; nothing was
chosen or dropped by content, and each story is cut at its last sentence end at
or before 500 characters to keep the file small. The file records its source's
sha256. On 2026-09-21 the generator was re-run and reproduced the committed file
byte for byte, and five rows (0, 17, 43, 88, 119) were checked by a route that
does not share the generator's parser: the row's prompt and story were ENCODED
and the byte string `USER prompt EOT BOT story` was found exactly once in the raw
`.bin`.

WHAT IS WORTH READING HERE
--------------------------
An instrument nobody has tried to break is a number generator, so two of these
tests are about breaking it. `test_replace_alternate_sentences_raises_uer_*` is
the can-fail test: a mutation that deletes introductions must move the rate, by
a margin that was measured. `test_plain_interleave_is_not_detected_known_blindness`
pins the opposite: a mutation a reader would call WORSE leaves the rate where it
was. That test passing is not good news. It is there so the limit stays a
measured fact that a future change to the instrument has to confront, rather
than a sentence in a docstring.

The fixture readings asserted below (clean 3/120, replace-alternate 32/120,
interleave 2/120) are regenerated by running this file's `_readings()`; the
full-corpus counterparts are in `experiments/chat/_quality/coherence_v14.json`
under `corpus.mutations`.

Not part of the research protocol; no number here is a reported figure.
"""
from __future__ import annotations

import importlib.util
import json
import os
import statistics
import subprocess
import sys

import numpy as np
import pytest

from snnchat import coherence
from snnchat.coherence import anchored_topic, uer, unintroduced_entities
from snnchat.tokenizer import BOS, EOT, ChatTokenizer

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

_SPEC = importlib.util.spec_from_file_location(
    "coherence_score", os.path.join(REPO, "scripts", "chat", "coherence_score.py"))
scorer = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(scorer)
FIXTURE = os.path.join(REPO, "tests", "fixtures", "chat_stories_uer.json")

#: The mutation partner of fixture story `i` is story `(i + PARTNER) % n` -- the
#: same fixed offset `scripts/chat/coherence_score.py` uses on the full corpus, so
#: the fixture readings and the artifact's are the same experiment at two sizes.
PARTNER = 7


def _pad(text: str, to: int = 260) -> str:
    """`text` padded past the window with a sentence that contains no "the"."""
    filler = " She smiled and he smiled and they all sat down for a while."
    while len(text) < to:
        text += filler
    return text


def _stories() -> list[str]:
    with open(FIXTURE, encoding="utf-8") as fh:
        return [row["story"] for row in json.load(fh)["rows"]]


def _readings() -> dict[str, dict]:
    stories = _stories()
    n = len(stories)
    partner = [stories[(i + PARTNER) % n] for i in range(n)]
    pairs = list(zip(stories, partner, strict=True))
    return {
        "clean": uer(stories),
        "replace": uer([coherence.replace_alternate_sentences(a, b) for a, b in pairs]),
        "interleave": uer([coherence.interleave_sentences(a, b) for a, b in pairs]),
    }


